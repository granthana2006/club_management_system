SELECT 'users'               AS table_name, COUNT(*) AS record_count FROM users
UNION ALL
SELECT 'club_categories'     AS table_name, COUNT(*) AS record_count FROM club_categories
UNION ALL
SELECT 'clubs'               AS table_name, COUNT(*) AS record_count FROM clubs
UNION ALL
SELECT 'club_memberships'    AS table_name, COUNT(*) AS record_count FROM club_memberships
UNION ALL
SELECT 'events'              AS table_name, COUNT(*) AS record_count FROM events
UNION ALL
SELECT 'event_registrations' AS table_name, COUNT(*) AS record_count FROM event_registrations
UNION ALL
SELECT 'attendance'          AS table_name, COUNT(*) AS record_count FROM attendance;

SELECT
    event_id,
    club_id,
    event_name,
    event_date,
    start_time,
    end_time,
    event_status,
    lifecycle_status,
    max_capacity,
    registered_count,
    seats_remaining
FROM v_event_overview
ORDER BY event_date ASC, start_time ASC;